package razorpay

import (
	"bytes"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"time"
)

type OrderRequest struct {
	Amount   int               `json:"amount"` // amount in paise
	Currency string            `json:"currency"`
	Receipt  string            `json:"receipt,omitempty"`
	Notes    map[string]string `json:"notes,omitempty"`
}

type OrderResponse struct {
	ID        string `json:"id"`
	Entity    string `json:"entity"`
	Amount    int    `json:"amount"`
	Currency  string `json:"currency"`
	Receipt   string `json:"receipt"`
	Status    string `json:"status"`
	CreatedAt int64  `json:"created_at"`
}

// CreateOrder calls Razorpay's order creation API (Standard Orders API).
func CreateOrder(req OrderRequest) (*OrderResponse, error) {
	keyID := os.Getenv("RAZORPAY_KEY_ID")
	keySecret := os.Getenv("RAZORPAY_KEY_SECRET")
	if keyID == "" || keySecret == "" {
		return nil, fmt.Errorf("razorpay credentials not set in environment")
	}

	bodyBytes, err := json.Marshal(req)
	if err != nil {
		return nil, err
	}

	httpReq, err := http.NewRequest("POST", "https://api.razorpay.com/v1/orders", bytes.NewReader(bodyBytes))
	if err != nil {
		return nil, err
	}
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.SetBasicAuth(keyID, keySecret)

	client := &http.Client{Timeout: 15 * time.Second}
	resp, err := client.Do(httpReq)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil, fmt.Errorf("razorpay order creation failed (status %d): %s", resp.StatusCode, string(respBody))
	}

	var orderResp OrderResponse
	if err := json.Unmarshal(respBody, &orderResp); err != nil {
		return nil, fmt.Errorf("failed to parse razorpay order response: %w", err)
	}
	return &orderResp, nil
}

// VerifySignature validates the hex-encoded HMAC-SHA256 signature generated by Razorpay Checkout.
// Algorithm: HMAC-SHA256(order_id + "|" + payment_id, KEY_SECRET)
func VerifySignature(orderID, paymentID, signature string) (bool, error) {
	keySecret := os.Getenv("RAZORPAY_KEY_SECRET")
	if keySecret == "" {
		return false, fmt.Errorf("razorpay secret not set in environment")
	}

	payload := fmt.Sprintf("%s|%s", orderID, paymentID)
	mac := hmac.New(sha256.New, []byte(keySecret))
	mac.Write([]byte(payload))
	expectedSignature := hex.EncodeToString(mac.Sum(nil))

	return hmac.Equal([]byte(expectedSignature), []byte(signature)), nil
}
